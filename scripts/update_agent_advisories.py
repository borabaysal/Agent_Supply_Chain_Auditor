#!/usr/bin/env python3
"""Regenerate asca/agentadv_data.py: known vulnerabilities in coding agents other than Hermes.

Sources (read-only, GitHub REST API; set GITHUB_TOKEN to raise the rate limit):
- the global GitHub Advisory Database, per npm package (what OSV.dev mirrors), and
- each vendor's own repository security advisories, which sometimes never reach the global
  database (e.g. GHSA-5j29-h97v-84ch for Claude Code, GHSA-r5pp-p5r8-466r for goose).

Run from the repo root:  python3 scripts/update_agent_advisories.py
"""
from __future__ import annotations

import json
import os
import pprint
import sys
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from asca.agentvers import AGENTS  # noqa: E402

API = "https://api.github.com"


def get(url: str):
    h = {"Accept": "application/vnd.github+json", "User-Agent": "asca-advisory-update"}
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("ASCA_GITHUB_TOKEN")
    if tok:
        h["Authorization"] = f"Bearer {tok}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=h), timeout=30) as r:  # noqa: S310
        return json.load(r)


def pages(url: str) -> list:
    out, page = [], 1
    while True:
        d = get(f"{url}{'&' if '?' in url else '?'}per_page=100&page={page}")
        out += d
        if len(d) < 100:
            return out
        page += 1


def main() -> int:
    data: dict[str, list] = {}
    for key, spec in AGENTS.items():
        rows: dict[str, dict] = {}
        if spec.get("npm"):
            for a in pages(f"{API}/advisories?ecosystem=npm&affects={spec['npm']}"):
                ranges = [v.get("vulnerable_version_range") for v in a["vulnerabilities"]
                          if (v.get("package") or {}).get("name") == spec["npm"] and v.get("vulnerable_version_range")]
                fixed = sorted({v.get("first_patched_version") for v in a["vulnerabilities"]
                                if (v.get("package") or {}).get("name") == spec["npm"] and v.get("first_patched_version")})
                if ranges:
                    rows[a["ghsa_id"]] = {"id": a["ghsa_id"], "cve": a.get("cve_id") or "", "severity": a["severity"],
                                          "summary": (a.get("summary") or "")[:200], "ranges": ranges,
                                          "fixed": ", ".join(fixed), "source": "GitHub Advisory Database",
                                          "url": a.get("html_url", "")}
        for repo in spec.get("repos", ()):
            for a in get(f"{API}/repos/{repo}/security-advisories?per_page=100&state=published"):
                vulns = [v for v in a.get("vulnerabilities") or []
                         if (v.get("package") or {}).get("name") in spec["repo_packages"]]
                if not vulns or a["ghsa_id"] in rows:
                    continue
                rows[a["ghsa_id"]] = {"id": a["ghsa_id"], "cve": a.get("cve_id") or "",
                                      "severity": a.get("severity") or "medium",
                                      "summary": (a.get("summary") or "")[:200],
                                      "ranges": [v["vulnerable_version_range"] for v in vulns
                                                 if v.get("vulnerable_version_range")],
                                      "fixed": ", ".join(sorted({str(v.get("patched_versions") or "").strip()
                                                                 for v in vulns} - {""})),
                                      "source": f"{repo} repository advisory", "url": a.get("html_url", "")}
        data[key] = sorted(rows.values(), key=lambda r: r["id"])
        print(f"{key}: {len(data[key])} advisories", file=sys.stderr)
    body = ('"""Generated by scripts/update_agent_advisories.py; do not edit by hand."""\n\n'
            f'REVIEWED_AT = "{date.today().isoformat()}"\n\nADVISORIES = ' + pprint.pformat(data, width=118, sort_dicts=True)
            + "\n")
    (ROOT / "asca" / "agentadv_data.py").write_text(body, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
